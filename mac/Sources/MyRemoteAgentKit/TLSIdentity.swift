import Foundation
import MyRemoteCore
import Security

public enum TLSIdentityError: Error, CustomStringConvertible {
    case opensslFailed(step: String, status: Int32, output: String)
    case opensslMissing(String)
    case importFailed(OSStatus)
    case noIdentityInArchive
    case certificateUnavailable(OSStatus)

    public var description: String {
        switch self {
        case let .opensslFailed(step, status, output):
            return "openssl \(step) failed with status \(status): \(output)"
        case let .opensslMissing(path):
            return "\(path) is missing or not executable"
        case let .importFailed(status):
            let text = SecCopyErrorMessageString(status, nil) as String? ?? "unknown"
            return "PKCS#12 import failed (\(status)): \(text)"
        case .noIdentityInArchive:
            return "the PKCS#12 archive contains no identity"
        case let .certificateUnavailable(status):
            return "cannot read the certificate of the TLS identity (\(status))"
        }
    }
}

/// The agent's self-signed TLS identity.
public struct TLSIdentity {
    public let identity: SecIdentity
    /// DER encoding of the leaf certificate, exactly what the client hashes.
    public let certificateDER: Data
    /// `fp` of the contract: SHA-256 of `certificateDER`, 64 lowercase hex characters.
    public let fingerprint: String
}

/// Creates the identity once and loads the same one on every later start.
///
/// The key and certificate are generated by `/usr/bin/openssl` and persisted as a
/// PKCS#12 archive (`identity.p12`, mode 0600) in the state directory. Loading uses
/// `SecPKCS12Import` with `kSecImportToMemoryOnly`, so the identity never enters a
/// keychain: no keychain prompt, nothing left behind in the login keychain.
public enum TLSIdentityStore {
    public static let opensslPath = "/usr/bin/openssl"

    /// Protects nothing by itself: PKCS#12 requires a passphrase, and
    /// `SecPKCS12Import` rejects an empty one. Confidentiality of the private key
    /// comes from the 0600 file in the 0700 state directory.
    static let archivePassphrase = "myremote"

    /// How often generation is retried when the fresh archive cannot be imported.
    ///
    /// This is not paranoia. LibreSSL 3.3.6 (macOS's /usr/bin/openssl) writes the
    /// EC private scalar without leading zero bytes, so roughly one key in 256 is
    /// encoded in 31 bytes instead of 32. Security.framework does not accept such
    /// a key: `SecPKCS12Import` reports success and returns no items. The outcome is
    /// a fixed property of the generated key, so a new key is the fix, and an
    /// archive that imported once imports every time.
    static let generationAttempts = 8

    public static func loadOrCreate(in store: StateStore) throws -> TLSIdentity {
        try loadOrCreate(in: store, generate: generatePKCS12(workingIn:))
    }

    /// - Parameter generate: produces PKCS#12 bytes; replaceable in tests.
    static func loadOrCreate(in store: StateStore, generate: (URL) throws -> Data) throws -> TLSIdentity {
        if let archive = store.read(StateStore.identityFile) {
            do {
                return try importIdentity(fromPKCS12: archive)
            } catch {
                // Keep the unreadable file for inspection and start over. This changes
                // the fingerprint, so paired phones will have to pair again.
                let aside = store.url(for: StateStore.identityFile + ".unreadable")
                try? FileManager.default.removeItem(at: aside)
                try? FileManager.default.moveItem(at: store.url(for: StateStore.identityFile), to: aside)
                Log.error("stored TLS identity is unreadable (\(error)); generating a new one")
            }
        }
        var lastError: Error = TLSIdentityError.noIdentityInArchive
        for _ in 0..<generationAttempts {
            let archive = try generate(store.directory)
            do {
                // Persist only what has been proven to import.
                let identity = try importIdentity(fromPKCS12: archive)
                try store.write(archive, to: StateStore.identityFile)
                return identity
            } catch let error as TLSIdentityError {
                lastError = error
            }
        }
        throw lastError
    }

    // MARK: Import

    public static func importIdentity(fromPKCS12 archive: Data) throws -> TLSIdentity {
        let options: [String: Any] = [
            kSecImportExportPassphrase as String: archivePassphrase,
            kSecImportToMemoryOnly as String: true,
        ]
        var items: CFArray?
        let status = SecPKCS12Import(archive as CFData, options as CFDictionary, &items)
        guard status == errSecSuccess else { throw TLSIdentityError.importFailed(status) }
        guard let entries = items as? [[String: Any]],
              let value = entries.compactMap({ $0[kSecImportItemIdentity as String] }).first
        else { throw TLSIdentityError.noIdentityInArchive }
        // The dictionary value is typed `Any`; the documented type is SecIdentity.
        let identity = value as! SecIdentity

        var certificate: SecCertificate?
        let copyStatus = SecIdentityCopyCertificate(identity, &certificate)
        guard copyStatus == errSecSuccess, let certificate else {
            throw TLSIdentityError.certificateUnavailable(copyStatus)
        }
        let der = SecCertificateCopyData(certificate) as Data
        return TLSIdentity(
            identity: identity,
            certificateDER: der,
            fingerprint: CertificateFingerprint.sha256Hex(ofDER: der))
    }

    // MARK: Generation

    /// Generates a P-256 key and a self-signed certificate valid for 20 years and
    /// returns them as PKCS#12 bytes. Intermediate files live in a private 0700
    /// directory under `directory` and are removed before returning.
    static func generatePKCS12(workingIn directory: URL) throws -> Data {
        guard FileManager.default.isExecutableFile(atPath: opensslPath) else {
            throw TLSIdentityError.opensslMissing(opensslPath)
        }
        let work = directory.appendingPathComponent(".identity-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(
            at: work, withIntermediateDirectories: false, attributes: [.posixPermissions: 0o700])
        defer { try? FileManager.default.removeItem(at: work) }

        // A private config keeps the result independent of the system openssl.cnf.
        let config = """
        [req]
        distinguished_name = dn
        x509_extensions = ext
        prompt = no
        [dn]
        CN = MyRemote Agent
        [ext]
        basicConstraints = critical,CA:TRUE
        subjectKeyIdentifier = hash
        subjectAltName = DNS:myremote.local
        """
        let configURL = work.appendingPathComponent("openssl.cnf")
        try Data(config.utf8).write(to: configURL)

        try openssl("ecparam", ["ecparam", "-genkey", "-name", "prime256v1", "-noout", "-out", "key.pem"], in: work)
        try openssl("req", [
            "req", "-x509", "-new", "-config", "openssl.cnf", "-key", "key.pem",
            "-sha256", "-days", "7300", "-out", "cert.pem",
        ], in: work)
        // LibreSSL's default PKCS#12 encryption (3DES / SHA-1 MAC) is the variant
        // SecPKCS12Import understands.
        try openssl("pkcs12", [
            "pkcs12", "-export", "-inkey", "key.pem", "-in", "cert.pem",
            "-name", "MyRemote Agent", "-passout", "pass:\(archivePassphrase)", "-out", "identity.p12",
        ], in: work)

        return try Data(contentsOf: work.appendingPathComponent("identity.p12"))
    }

    private static func openssl(_ step: String, _ arguments: [String], in directory: URL) throws {
        let process = Process()
        process.executableURL = URL(fileURLWithPath: opensslPath)
        process.arguments = arguments
        process.currentDirectoryURL = directory
        // Minimal environment: no OPENSSL_CONF or RANDFILE surprises from the caller.
        process.environment = ["PATH": "/usr/bin:/bin", "HOME": directory.path]
        process.standardInput = FileHandle.nullDevice
        process.standardOutput = FileHandle.nullDevice
        let errorPipe = Pipe()
        process.standardError = errorPipe

        // Files created by openssl inherit this umask: owner-only.
        let previousMask = umask(0o077)
        defer { umask(previousMask) }
        do {
            try process.run()
        } catch {
            throw TLSIdentityError.opensslFailed(step: step, status: -1, output: "\(error.localizedDescription)")
        }
        let errorOutput = errorPipe.fileHandleForReading.readDataToEndOfFile()
        process.waitUntilExit()
        guard process.terminationStatus == 0 else {
            throw TLSIdentityError.opensslFailed(
                step: step, status: process.terminationStatus,
                output: String(decoding: errorOutput, as: UTF8.self).trimmingCharacters(in: .whitespacesAndNewlines))
        }
    }
}
